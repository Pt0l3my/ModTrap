import tempfile
import unittest
from pathlib import Path

from modtrap import instance, model, plugin
from tests import _fixtures as fx


class IniTests(unittest.TestCase):
    def test_values(self):
        v = instance.ini_value
        self.assertEqual(v("@ByteArray(C:\\\\Games\\\\Skyrim)"), "C:\\Games\\Skyrim")
        self.assertEqual(v('"a \\"quoted\\" value"'), 'a "quoted" value')
        self.assertEqual(v("caf\\xe9"), "caf\xe9")
        self.assertEqual(v("C:/Modlists/Example/mods"), "C:/Modlists/Example/mods")

    def test_sections_and_arrays(self):
        ini = instance.parse_ini("[General]\ngameName=Skyrim Special Edition\n; a comment\n"
                                 "[customExecutables]\nsize=1\n1\\title=xEdit\n1\\binary=C:/Tools/x.exe\n")
        self.assertEqual(ini["General"]["gameName"], "Skyrim Special Edition")
        self.assertEqual(ini["customExecutables"]["1\\title"], "xEdit")


class ListTests(unittest.TestCase):
    def test_modlist(self):
        text = "# This file was automatically generated by Mod Organizer.\r\n+Top\r\n-Off\r\n*DLC: X\r\nBare\r\n\r\n"
        self.assertEqual(instance.parse_modlist(text), [("+", "Top"), ("-", "Off"), ("*", "DLC: X"), ("+", "Bare")])

    def test_plugins(self):
        text = "# comment\r\n*On.esp\r\nOff.esp\r\n*\r\n"
        self.assertEqual(instance.parse_plugins(text), [("On.esp", True), ("Off.esp", False)])


class InstanceTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = fx.small_list(Path(self.tmp.name) / "Example List")

    def tearDown(self):
        self.tmp.cleanup()

    def test_not_an_instance(self):
        with self.assertRaises(instance.Unusable):
            instance.load(Path(self.tmp.name))

    def test_mods_and_priorities(self):
        inst = instance.load(self.root)
        self.assertEqual(inst.profile, "Default")
        names = [(m.name, m.priority, m.enabled, m.kind) for m in inst.mods]
        self.assertEqual(names, [
            (instance.GAME, -1, True, "game"),
            ("DLC: Dawnguard", 0, True, "foreign"),
            ("Bramble", 1, True, "mod"),
            ("Old Lantern", 2, False, "mod"),
            ("Lantern", 3, True, "mod"),
            ("Quill", 4, True, "mod"),
            ("Outputs_separator", 5, False, "separator"),
            ("Bramble - Lantern Patch", 6, True, "mod"),
            (instance.OVERWRITE, 7, True, "overwrite"),
        ])
        self.assertEqual(inst.mod("bramble").plugins, ("Bramble.esp",))
        self.assertEqual(inst.executables[0].title, "xEdit")
        self.assertEqual(inst.notes, [])

    def test_load_order(self):
        inst = instance.load(self.root)
        self.assertEqual([n for n, _ in inst.load_order],
                         list(fx.GAME_PLUGINS) + ["Bramble.esp", "Lantern.esp", "Quill.esp",
                                                  "BrambleLanternPatch.esp"])
        self.assertTrue(all(a for _, a in inst.load_order))

    def test_unlisted_folder_and_missing_folder(self):
        (self.root / "mods" / "Stray").mkdir()
        p = self.root / "profiles" / "Default" / "modlist.txt"
        p.write_bytes(p.read_bytes() + b"+Ghost\r\n")
        inst = instance.load(self.root)
        stray = inst.mod("Stray")
        self.assertFalse(stray.enabled)
        self.assertFalse(stray.listed)
        self.assertIsNone(inst.mod("Ghost"))
        self.assertEqual(len(inst.notes), 2)

    def test_creation_club_plugins_are_primary(self):
        fx.write(self.root / "Game" / "Skyrim.ccc", "ccInvented001.esm\r\nccInvented002.esl\r\n")
        inst = instance.load(self.root)
        self.assertEqual(inst.primary[-2:], ("ccInvented001.esm", "ccInvented002.esl"))


class ModelTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = fx.small_list(Path(self.tmp.name) / "Example List")

    def tearDown(self):
        self.tmp.cleanup()

    def build(self):
        return model.build(instance.load(self.root))

    def test_clean_list(self):
        m = self.build()
        self.assertEqual(m.issues, [])
        lantern = m.row("lantern.esp")
        self.assertEqual(lantern.source, "Lantern")          # the disabled Old Lantern does not count
        self.assertEqual(lantern.masters, ("Skyrim.esm", "Bramble.esp"))
        self.assertEqual(lantern.position, 6)
        self.assertEqual(m.row("BrambleLanternPatch.esp").kind, "esp+esl")
        self.assertEqual(m.row("Skyrim.esm").kind, "esm")
        self.assertTrue(m.row("Skyrim.esm").primary)

    def test_dependants(self):
        m = self.build()
        self.assertEqual(m.row("Bramble.esp").dependants, ["Lantern.esp", "BrambleLanternPatch.esp"])
        bramble = m.instance.mod("Bramble")
        self.assertEqual([r.name for r in m.dependants_of_mod(bramble)], ["Lantern.esp", "BrambleLanternPatch.esp"])
        self.assertEqual(m.dependants_of_mod(m.instance.mod("Quill")), [])

    def test_disabling_the_mod_is_what_breaks_the_list(self):
        # The situation ModTrap exists for: with Bramble disabled, its dependants miss a master.
        p = self.root / "profiles" / "Default" / "modlist.txt"
        p.write_bytes(p.read_bytes().replace(b"+Bramble\r\n", b"-Bramble\r\n"))
        m = self.build()
        self.assertEqual([(i.plugin, i.master, i.what) for i in m.issues],
                         [("Lantern.esp", "Bramble.esp", "missing"),
                          ("BrambleLanternPatch.esp", "Bramble.esp", "missing")])
        self.assertIsNone(m.row("Bramble.esp").source)

    def test_inactive_master(self):
        p = self.root / "profiles" / "Default" / "plugins.txt"
        p.write_bytes(p.read_bytes().replace(b"*Bramble.esp", b"Bramble.esp"))
        m = self.build()
        self.assertEqual({(i.plugin, i.what) for i in m.issues},
                         {("Lantern.esp", "inactive"), ("BrambleLanternPatch.esp", "inactive")})

    def test_higher_mod_wins_and_overwrite_wins_all(self):
        fx.write(self.root / "mods" / "Quill" / "Lantern.esp", plugin.build(("Skyrim.esm",)))
        m = self.build()
        row = m.row("Lantern.esp")
        self.assertEqual((row.source, row.also_in), ("Quill", ("Lantern",)))
        self.assertEqual(m.row("Bramble.esp").dependants, ["BrambleLanternPatch.esp"])
        fx.write(self.root / "overwrite" / "Lantern.esp", plugin.build(("Skyrim.esm", "Bramble.esp")))
        self.assertEqual(self.build().row("Lantern.esp").source, instance.OVERWRITE)

    def test_unreadable_plugin_is_reported_not_guessed(self):
        fx.write(self.root / "mods" / "Quill" / "Quill.esp", b"not a plugin at all")
        m = self.build()
        self.assertTrue(m.row("Quill.esp").unreadable)
        self.assertEqual(m.row("Quill.esp").masters, ())


if __name__ == "__main__":
    unittest.main()
