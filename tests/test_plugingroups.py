HEAD = b"# This file was automatically generated by Mod Organizer.\r\n"
FILE = HEAD + b"Core.esm|Base\r\nGenerated.esp|Outputs\r\nLantern.esp|Things\r\nQuill.esp|Things\r\n"


class TheFile(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.pdir = Path(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def test_it_is_read_as_mo2s_plugin_manager_reads_it(self):
        got, bad = plugingroups.parse("# a comment\r\n\r\nCore.esm|Base\r\nQuill.esp|Things, and more (1)\r\nno bar here\r\ntwo|bars|here\r\n|nameless\r\nEmpty.esp|\r\n")
        self.assertEqual((got, bad), ({"core.esm": "Base", "quill.esp": "Things, and more (1)"}, 3))
        self.assertIsNone(plugingroups.read(self.pdir))                 # no file: this MO2 keeps no groups
        (self.pdir / plugingroups.NAME).write_bytes(FILE)
        self.assertEqual(plugingroups.read(self.pdir)["lantern.esp"], "Things")

    def test_a_mods_separator_is_the_first_one_below_it(self):
        mods = [("+", "Outputs_separator"), ("+", "Thistle"), ("-", "Beacon"), ("+", "Gear_separator"), ("+", "Quill")]
        self.assertEqual([plugingroups.separator_of(mods, n) for n in ("thistle", "Beacon", "Quill", "Absent")], ["Gear", "Gear", "", ""])

    def test_a_new_plugins_group(self):
        groups = {"core.esm": "Base", "quill.esp": "Things", "lantern.esp": "Things", "generated.esp": "Outputs"}
        order = [CORE, "Quill.esp", "New.esp", "Lantern.esp", "Generated.esp"]
        self.assertEqual(plugingroups.for_new(order, groups, "New.esp", "Gear"), "Things")          # inside a group: in it
        order = [CORE, "Quill.esp", "Lantern.esp", "New.esp", "Generated.esp"]
        self.assertEqual(plugingroups.for_new(order, groups, "New.esp", "Gear"), "Gear")            # between two: its mod's separator names a new one
        self.assertEqual(plugingroups.for_new(order, groups, "New.esp", "Outputs"), "Outputs")      # a neighbour's: it joins
        self.assertEqual(plugingroups.for_new(order, groups, "New.esp", ""), "")                    # no separator, no group
        self.assertEqual(plugingroups.for_new(order, groups, "New.esp", "Base"), "")                # the name is in use elsewhere: not a second group of it
        self.assertEqual(plugingroups.for_new([CORE, "New.esp"], {}, "New.esp", " a | b "), "a b")

    def test_a_moved_plugins_group(self):
        groups = {"core.esm": "Base", "quill.esp": "Things", "lantern.esp": "Things", "thistle.esp": "Things", "generated.esp": "Outputs"}
        was = [CORE, "Quill.esp", "Lantern.esp", "Thistle.esp", "Generated.esp"]
        move = lambda now, name: plugingroups.after_move(was, now, groups, name)                    # noqa: E731
        self.assertEqual(move([CORE, "Quill.esp", "Generated.esp", "Lantern.esp", "Thistle.esp"], "Generated.esp"), "Things")      # into a group
        self.assertEqual(move([CORE, "Lantern.esp", "Quill.esp", "Thistle.esp", "Generated.esp"], "Quill.esp"), "Things")        # within its own
        self.assertEqual(move([CORE, "Quill.esp", "Thistle.esp", "Generated.esp", "Lantern.esp"], "Lantern.esp"), "")            # out of the middle of its own
        self.assertEqual(move([CORE, "Quill.esp", "Thistle.esp", "Lantern.esp", "Generated.esp"], "Lantern.esp"), "Things")      # to its edge: still in it
        alone = dict(groups, **{"generated.esp": "Outputs", "extra.esp": ""})
        self.assertEqual(plugingroups.after_move(was + ["Extra.esp"], was[:4] + ["Extra.esp", "Generated.esp"], alone, "Generated.esp"), "Outputs")   # alone in it: it goes along

    def test_only_the_lines_wanted_change(self):
        path = self.pdir / plugingroups.NAME
        with self.assertRaises(profile.Refused):
            plugingroups.set_groups(self.pdir, {"New.esp": "Gear"})     # ModTrap never makes the file
        path.write_bytes(FILE)
        ch = plugingroups.set_groups(self.pdir, {"Heather.esp": "Gear"})
        self.assertEqual(path.read_bytes(), HEAD + b"Core.esm|Base\r\nGenerated.esp|Outputs\r\nHeather.esp|Gear\r\nLantern.esp|Things\r\nQuill.esp|Things\r\n")
        self.assertEqual(ch.lines, [{"plugin": "Heather.esp", "group": "Gear", "was": ""}])
        plugingroups.set_groups(self.pdir, {"quill.esp": "Gear", "Core.esm": "", "Zeta.esp": "Last"})
        self.assertEqual(path.read_bytes(), HEAD + b"Generated.esp|Outputs\r\nHeather.esp|Gear\r\nLantern.esp|Things\r\nquill.esp|Gear\r\nZeta.esp|Last\r\n")
        same = path.read_bytes()
        self.assertEqual(plugingroups.set_groups(self.pdir, {"Zeta.esp": "Last", "Absent.esp": ""}).lines, [])
        self.assertEqual(path.read_bytes(), same)
        for name, group in (("A|B.esp", "X"), ("A.esp", "X|Y"), ("A.esp", " padded "), ("#A.esp", "X"), ("A.esp", "x" * 101)):
            with self.assertRaises(profile.Refused):
                plugingroups.set_groups(self.pdir, {name: group})
        self.assertEqual(path.read_bytes(), same)
        # A file with Unix line ends, and no end on its last line, keeps them.
        path.write_bytes(b"# made by hand\nCore.esm|Base")
        plugingroups.set_groups(self.pdir, {"Quill.esp": "Things"})
        self.assertEqual(path.read_bytes(), b"# made by hand\nCore.esm|Base\nQuill.esp|Things\n")


class TheGroupsInTheJobs(unittest.TestCase):
    def setUp(self):
        logbook.set_console(False)
        self.tmp = tempfile.TemporaryDirectory()
        os.environ["MODTRAP_HOME"] = str(Path(self.tmp.name) / "home")
        self.root = invented(Path(self.tmp.name) / "Example List")
        self.pdir = self.root / "profiles" / "Default"
        self.file = self.pdir / plugingroups.NAME
        self.file.write_bytes(FILE)
        self.api = api.Api()
        self.closed = True
        self.api.running = lambda image: not self.closed
        self.api.open(str(self.root), wait=True)
        self.api.changes = changes.Changes(self.api, require_probe=False)

    def tearDown(self):
        self.settle()
        os.environ.pop("MODTRAP_HOME", None)
        self.tmp.cleanup()
        logbook.set_console(True)

    def settle(self):
        for _ in range(600):
            if self.api.status == "ready" and not any(r["state"] in ("copying", "unpacking") for r in self.api._staged.values()):
                return
            time.sleep(0.01)
        self.fail("the modlist was not read again")

    def post(self, path, body):
        self.settle()
        got = self.api.post(path, body)[1]
        self.settle()
        return got

    def groups(self):
        got = self.api.get("/api/plugins", {})[1]
        return {r["name"]: r["mo2_group"] for r in got["plugins"] if r["name"] not in fx.GAME_PLUGINS}

    def events(self):
        return [(e["kind"], e.get("plugin"), e.get("group"), e.get("group_was")) for e in history.History(self.api.store.dir(self.api.session.id)).all() if e["kind"] == "plugin grouped"]

    def test_the_plugins_tab_gets_mo2s_groups_and_without_the_file_the_separators(self):
        got = self.api.get("/api/plugins", {})[1]
        self.assertEqual(got["groups"], "mo2")
        self.assertEqual(self.groups(), {CORE: "Base", "Quill.esp": "Things", "Lantern.esp": "Things", "Generated.esp": "Outputs"})
        self.file.unlink()
        self.api.open(str(self.root), wait=True)
        got = self.api.get("/api/plugins", {})[1]
        self.assertEqual((got["groups"], {r["mo2_group"] for r in got["plugins"]}), ("separators", {""}))
        with self.assertRaises(api.Bad) as e:
            self.post("/api/list/plugins/group", {"plugins": ["Quill.esp"], "group": "Gear"})
        self.assertIn("keeps no plugin groups", str(e.exception))
        self.post("/api/list/set", {"mods": ["Thistle"], "on": True})          # and nothing makes the file
        self.assertFalse(self.file.exists())

    def test_a_plugin_is_given_a_group_at_the_owners_word_and_back(self):
        got = self.post("/api/list/plugins/group", {"plugins": ["Generated.esp"], "group": "Made by tools"})
        self.assertEqual((got["done"], got["text"]), (True, "Put Generated.esp in the group “Made by tools”"))
        self.assertEqual(self.file.read_bytes(), FILE.replace(b"Generated.esp|Outputs", b"Generated.esp|Made by tools"))
        self.assertEqual(self.groups()["Generated.esp"], "Made by tools")
        self.assertEqual(self.events(), [("plugin grouped", "Generated.esp", "Made by tools", "Outputs")])
        self.assertEqual(self.post("/api/list/plugins/group", {"plugins": ["Generated.esp"], "group": "Made by tools"}), {"done": False, "nothing": True})
        out = self.post("/api/list/plugins/group", {"plugins": ["Quill.esp", "Lantern.esp"], "group": ""})
        self.assertEqual(out["text"], "Took Quill.esp and 1 more out of their groups")
        self.assertEqual(self.file.read_bytes(), HEAD + b"Core.esm|Base\r\nGenerated.esp|Made by tools\r\n")
        self.assertEqual([(j["op"], j["undone"]) for j in self.api.changes.list_jobs()], [("plugin group", ""), ("plugin group", "")])
        for _ in range(2):
            back = self.post("/api/list/undo", {})
            self.assertEqual(back["how"], "whole")
        self.assertEqual(self.file.read_bytes(), FILE)
        self.assertEqual(self.events()[-1], ("plugin grouped", "Generated.esp", "Outputs", "Made by tools"))
        for body in ({"plugins": ["Quill.esp"], "group": "a|b"}, {"plugins": ["Absent.esp"], "group": "Gear"}, {"plugins": ["Quill.esp"], "group": "x" * 101}, {"plugins": [], "group": "Gear"}):
            with self.assertRaises(api.Bad):
                self.post("/api/list/plugins/group", body)
        self.closed = False                                                     # MO2 open: it would write its own groups back
        with self.assertRaises(api.Bad):
            self.post("/api/list/plugins/group", {"plugins": ["Quill.esp"], "group": "Gear"})
        self.assertEqual(self.file.read_bytes(), FILE)

    def test_an_undo_after_mo2_wrote_its_groups_turns_back_only_its_own_line(self):
        self.post("/api/list/plugins/group", {"plugins": ["Generated.esp"], "group": "Made by tools"})
        self.file.write_bytes(self.file.read_bytes().replace(b"Lantern.esp|Things", b"Lantern.esp|Lights"))       # MO2, since
        self.api.open(str(self.root), wait=True)
        back = self.post("/api/list/undo", {})
        self.assertEqual((back["how"], back["notes"]), ("by line", []))
        self.assertEqual(self.file.read_bytes(), FILE.replace(b"Lantern.esp|Things", b"Lantern.esp|Lights"))
        # A line changed again since stays, and that is said.
        self.post("/api/list/plugins/group", {"plugins": ["Quill.esp"], "group": "Gear"})
        self.file.write_bytes(self.file.read_bytes().replace(b"Quill.esp|Gear", b"Quill.esp|Elsewhere"))
        self.api.open(str(self.root), wait=True)
        back = self.post("/api/list/undo", {})
        self.assertEqual((back["how"], back["notes"]), ("by line", ["Quill.esp keeps the group it has now: it was changed again since"]))
        self.assertIn(b"Quill.esp|Elsewhere", self.file.read_bytes())

    def test_a_plugin_new_to_the_load_order_gets_its_group(self):
        # Beacon's master goes to the end of the masters' block, between Core (Base) and Quill (Things): its mod
        # stands under the separator “Gear”, which no plugin carries yet, so that names a new group.
        self.post("/api/list/set", {"mods": ["Beacon"], "on": True})
        self.assertEqual(self.groups()["Beacon.esm"], "Gear")
        self.assertIn(b"Beacon.esm|Gear\r\nCore.esm|Base\r\n", self.file.read_bytes())
        # Thistle's plugin goes to the end, after the tool's output: “Gear” is in use elsewhere now and no neighbour
        # has it, so the plugin is left without a group rather than under a second “Gear”.
        self.post("/api/list/set", {"mods": ["Thistle"], "on": True, "sure": True})
        self.assertEqual(self.groups()["Thistle.esp"], "")
        self.assertNotIn(b"Thistle.esp", self.file.read_bytes())
        for _ in range(2):
            self.assertEqual(self.post("/api/list/undo", {})["how"], "whole")
        self.assertEqual(self.file.read_bytes(), FILE)

    def test_a_plugin_placed_inside_a_group_is_in_it(self):
        self.file.write_bytes(FILE.replace(b"Core.esm|Base", b"Core.esm|Things"))
        self.api.open(str(self.root), wait=True)
        self.post("/api/list/set", {"mods": ["Beacon"], "on": True})
        self.assertEqual(self.groups()["Beacon.esm"], "Things")

    def test_a_moved_plugin_joins_the_group_it_lands_in_and_goes_back_with_its_own(self):
        got = self.post("/api/list/plugins/move", {"plugin": "Generated.esp", "before": "Lantern.esp"})
        self.assertEqual((got["group"], got["group_was"]), ("Things", "Outputs"))
        self.assertTrue(got["text"].endswith("into the group “Things”"))
        self.assertEqual(self.groups()["Generated.esp"], "Things")
        self.assertEqual(self.post("/api/list/undo", {})["how"], "whole")
        self.assertEqual(self.file.read_bytes(), FILE)
        # By line, after MO2 wrote its lists since: the plugin goes back, and its group with it.
        self.post("/api/list/plugins/move", {"plugin": "Generated.esp", "before": "Lantern.esp"})
        self.file.write_bytes(self.file.read_bytes().replace(b"Core.esm|Base", b"Core.esm|Game"))
        self.api.open(str(self.root), wait=True)
        self.assertEqual(self.post("/api/list/undo", {})["how"], "by line")
        self.assertEqual(self.file.read_bytes(), FILE.replace(b"Core.esm|Base", b"Core.esm|Game"))
        self.assertEqual([r["name"] for r in self.api.get("/api/plugins", {})[1]["plugins"]][-2:], ["Lantern.esp", "Generated.esp"])
        # A move within its own group changes no group, and no line of the file.
        self.post("/api/list/plugins/group", {"plugins": ["Generated.esp"], "group": "Things"})
        same = self.file.read_bytes()
        got = self.post("/api/list/plugins/move", {"plugin": "Generated.esp", "before": "Lantern.esp"})
        self.assertNotIn("group", got)
        self.assertEqual(self.file.read_bytes(), same)

    def test_a_plugin_let_go_on_a_groups_line_joins_that_group(self):
        """MT77."""
        # Moved to the edge of another group, a plugin does not join it; let go on that group's line, it does.
        plain = self.post("/api/list/plugins/move", {"plugin": "Lantern.esp", "before": ""})
        self.assertEqual((plain["group"], plain["group_was"], self.order_names()[-2:]), ("", "Things", ["Generated.esp", "Lantern.esp"]))
        self.post("/api/list/undo", {})
        self.assertEqual(self.file.read_bytes(), FILE)
        got = self.post("/api/list/plugins/move", {"plugin": "Lantern.esp", "before": "", "group": "Outputs"})
        self.assertEqual((got["group"], got["group_was"]), ("Outputs", "Things"))
        self.assertTrue(got["text"].endswith("into the group “Outputs”"))
        self.post("/api/list/undo", {})
        self.assertEqual(self.file.read_bytes(), FILE)
        # It stands directly before the group's first plugin already: nothing moves, and it joins.
        got = self.post("/api/list/plugins/move", {"plugin": "Lantern.esp", "before": "Generated.esp", "group": "Outputs"})
        self.assertEqual((got["done"], got["text"]), (True, "Put Lantern.esp in the group “Outputs”"))
        self.assertEqual((self.groups()["Lantern.esp"], self.order_names()[-2:]), ("Outputs", ["Lantern.esp", "Generated.esp"]))
        self.post("/api/list/undo", {})
        # Where MO2's limits put it elsewhere than beside that group, the group named does not count.
        got = self.post("/api/list/plugins/move", {"plugin": "Generated.esp", "before": CORE, "group": "Base"})
        self.assertTrue(got["why"])
        self.assertEqual(self.groups()["Generated.esp"], "Things")              # it landed between Quill and Lantern
        with self.assertRaises(api.Bad):
            self.post("/api/list/plugins/move", {"plugin": "Lantern.esp", "before": "", "group": "a|b"})

    def order_names(self):
        return [r["name"] for r in self.api.get("/api/plugins", {})[1]["plugins"]]

    def test_an_uninstalled_mods_plugin_is_in_its_group_again_when_it_is_put_back(self):
        got = self.post("/api/list/uninstall", {"mods": ["Lantern"], "sure": True})
        self.assertEqual(self.file.read_bytes(), FILE)                          # its line stays: MO2 drops it when it next writes
        self.file.write_bytes(FILE.replace(b"Lantern.esp|Things\r\n", b""))     # MO2 ran, and did
        self.api.open(str(self.root), wait=True)
        back = self.post("/api/list/undo", {"job": got["job"]})
        self.assertEqual(back["how"], "by line")
        self.assertEqual(self.file.read_bytes(), FILE)
        self.assertEqual(self.groups()["Lantern.esp"], "Things")

    def test_an_installed_mods_plugin_gets_the_group_of_its_mods_separator(self):
        data = zipped(NEW_MOD)
        rec = self.api.upload("Heather-4711-2-1.zip", len(data), io.BytesIO(data))
        body = {"mods": [], "staged": [rec["id"]]}
        for _ in range(400):
            self.settle()
            got = self.api.post("/api/add", body)[1]
            if not got["looking"] and not got["unpacking"]:
                break
            time.sleep(0.02)
        done = self.post("/api/add/run", body)
        # The mod goes to the end of the section before the outputs (under “Gear”), its plugin directly before the
        # first plugin a tool made: between the groups “Things” and “Outputs”, so its separator names its group.
        self.assertEqual([r["name"] for r in self.api.get("/api/plugins", {})[1]["plugins"]][-3:], ["Lantern.esp", "Heather.esp", "Generated.esp"])
        self.assertEqual(self.groups()["Heather.esp"], "Gear")
        self.assertIn(("plugin grouped", "Heather.esp", "Gear", ""), self.events())
        self.post("/api/add/revert", {"job": done["job"]})
        self.assertEqual(self.file.read_bytes(), FILE)


