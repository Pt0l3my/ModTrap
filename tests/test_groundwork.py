class ProfileTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = fx.small_list(Path(self.tmp.name) / "Example List")
        self.pdir = self.root / "profiles" / "Default"

    def tearDown(self):
        self.tmp.cleanup()

    def test_disabling_a_mod_changes_one_character_and_nothing_else(self):
        before = (self.pdir / "modlist.txt").read_bytes()
        ch = profile.set_mods(self.pdir, {"bramble": False})
        after = (self.pdir / "modlist.txt").read_bytes()
        self.assertEqual(after, before.replace(b"+Bramble\r\n", b"-Bramble\r\n"))
        self.assertEqual(len(after), len(before))
        self.assertEqual(ch.lines, [{"mod": "Bramble", "from": "+", "to": "-", "priority": 1}])   # as MO2 numbers it
        self.assertNotEqual(ch.before, ch.after)
        inst = instance.load(self.root)
        self.assertFalse(inst.mod("Bramble").enabled)
        self.assertEqual(inst.mod("Bramble").priority, 1)                    # its place did not move
        # Back again gives the original file, byte for byte.
        profile.set_mods(self.pdir, {"Bramble": True})
        self.assertEqual((self.pdir / "modlist.txt").read_bytes(), before)

    def test_refusals_write_nothing(self):
        before = (self.pdir / "modlist.txt").read_bytes()
        for wanted, word in (({"Nobody": False}, "not in this profile"), ({"DLC: Dawnguard": False}, "not managed"),
                             ({"Bramble": False, "Nobody": False}, "Nobody")):
            with self.subTest(str(wanted)):
                with self.assertRaises(profile.Refused) as c:
                    profile.set_mods(self.pdir, wanted)
                self.assertIn(word, str(c.exception))
                self.assertEqual((self.pdir / "modlist.txt").read_bytes(), before)
        with self.assertRaises(profile.Refused):
            profile.set_mods(self.pdir, {"Bramble": False}, expect="0" * 64)     # planned against another file
        self.assertEqual((self.pdir / "modlist.txt").read_bytes(), before)
        ch = profile.set_mods(self.pdir, {"Old Lantern": False})                # already so: nothing to do
        self.assertEqual((ch.lines, ch.before), ([], ch.after))

    def test_a_new_mod_goes_on_top_and_can_be_taken_out_again(self):
        before = (self.pdir / "modlist.txt").read_bytes()
        (self.root / "mods" / "ModTrap - Example").mkdir()
        ch = profile.add_mod_on_top(self.pdir, "ModTrap - Example")
        lines = (self.pdir / "modlist.txt").read_bytes().split(b"\r\n")
        self.assertEqual(lines[:2], [b"# This file was automatically generated by Mod Organizer.", b"+ModTrap - Example"])
        inst = instance.load(self.root)
        top = max((m for m in inst.mods if m.kind == "mod"), key=lambda m: m.priority)
        self.assertEqual((top.name, ch.lines[0]["priority"]), ("ModTrap - Example", top.priority))
        with self.assertRaises(profile.Refused):
            profile.add_mod_on_top(self.pdir, "modtrap - example")
        profile.remove_mod_line(self.pdir, "ModTrap - Example")
        self.assertEqual((self.pdir / "modlist.txt").read_bytes(), before)

    def test_deactivating_a_plugin_keeps_the_order_and_the_encoding(self):
        p = self.pdir / "plugins.txt"
        p.write_bytes(p.read_bytes() + "*Caf\xe9 - Patch.esp\r\n".encode("cp1252"))       # as MO2 writes it on this PC
        before = p.read_bytes()
        ch = profile.set_plugins(self.pdir, {"Collection - Bramble.esp": False, "caf\xe9 - patch.esp": False})
        after = p.read_bytes()
        self.assertEqual(after, before.replace(b"*Collection - Bramble.esp", b"Collection - Bramble.esp")
                         .replace(b"*Caf\xe9 - Patch.esp", b"Caf\xe9 - Patch.esp"))
        self.assertEqual([(x["plugin"], x["to"]) for x in ch.lines],
                         [("Collection - Bramble.esp", "inactive"), ("Caf\xe9 - Patch.esp", "inactive")])
        m = model.build(instance.load(self.root))
        self.assertFalse(m.row("Collection - Bramble.esp").active)
        self.assertEqual(m.row("Collection - Bramble.esp").position, 9)      # its place in the load order did not move
        with self.assertRaises(profile.Refused):
            profile.set_plugins(self.pdir, {"Skyrim.esm": False})            # the game's own are never listed
        profile.set_plugins(self.pdir, {"Collection - Bramble.esp": True, "Caf\xe9 - Patch.esp": True})
        self.assertEqual(p.read_bytes(), before)


class SafeTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = fx.small_list(Path(self.tmp.name) / "Example List")
        self.pdir = self.root / "profiles" / "Default"
        self.safe = safe.Safe(Path(self.tmp.name) / "job" / "safe")
        self.lantern = self.root / "mods" / "Lantern" / "Lantern.esp"

    def tearDown(self):
        self.tmp.cleanup()

    def test_no_change_without_a_copy(self):
        with self.assertRaises(safe.Refused):
            self.safe.may_change(self.lantern)
        self.safe.take(self.lantern)
        self.safe.may_change(self.lantern)                          # now it may
        self.assertEqual(self.safe.take(self.lantern)["copy"], "0001-Lantern.esp")   # taken once only

    def test_revert_puts_everything_back_and_removes_what_was_made(self):
        original = self.lantern.read_bytes()
        modlist = (self.pdir / "modlist.txt").read_bytes()
        self.safe.take(self.lantern)
        self.safe.take(self.pdir / "modlist.txt")
        self.lantern.write_bytes(original + b"demastered")
        self.safe.wrote(self.lantern)
        profile.set_mods(self.pdir, {"Bramble": False})
        self.safe.wrote(self.pdir / "modlist.txt")
        made = fx.write(self.root / "mods" / "ModTrap - Example" / "Lantern.esp", b"ModTrap's own")
        self.safe.created(made)
        # A new start of ModTrap reads the same record back.
        again = safe.Safe(self.safe.folder)
        plan = again.check()
        self.assertEqual((len(plan["restore"]), plan["foreign"], len(plan["remove"])), (2, [], 1))
        again.revert()
        self.assertEqual(self.lantern.read_bytes(), original)
        self.assertEqual((self.pdir / "modlist.txt").read_bytes(), modlist)
        self.assertFalse(made.exists())
        self.assertFalse(made.parent.exists())                      # ModTrap's own folder, now empty, is gone too
        self.assertTrue(again.reverted)

    def test_revert_stops_if_something_else_changed_a_file_since(self):
        original = self.lantern.read_bytes()
        modlist = (self.pdir / "modlist.txt").read_bytes()
        self.safe.take(self.lantern)
        self.safe.take(self.pdir / "modlist.txt")
        self.lantern.write_bytes(original + b"demastered")
        self.safe.wrote(self.lantern)
        profile.set_mods(self.pdir, {"Bramble": False})
        self.safe.wrote(self.pdir / "modlist.txt")
        self.lantern.write_bytes(original + b"and then the owner edited it in xEdit")
        with self.assertRaises(safe.Refused) as c:
            self.safe.revert()
        self.assertIn("Lantern.esp", str(c.exception))
        self.assertNotEqual((self.pdir / "modlist.txt").read_bytes(), modlist)    # nothing at all was put back
        self.safe.revert(overwrite_foreign=True)                                   # the owner saw it and said yes
        self.assertEqual(self.lantern.read_bytes(), original)
        self.assertEqual((self.pdir / "modlist.txt").read_bytes(), modlist)


class HistoryTests(unittest.TestCase):
    def test_events_are_kept_in_order_and_say_where_things_were(self):
        with tempfile.TemporaryDirectory() as d:
            h = history.History(Path(d))
            h.add("mod disabled", mod="Bramble", priority=1,
                  plugins=[{"name": "Bramble.esp", "position": 5, "kind": "esp"}])
            h.add("plugin deactivated", plugin="Collection - Bramble.esp", position=9, plugin_kind="esp",
                  mod="Patch Collection", mod_priority=7)
            self.assertEqual(sorted(history.History(Path(d)).disabled_now()),
                             ["mod:bramble", "plugin:collection - bramble.esp"])
            h.add("mod enabled", mod="Bramble", priority=1)
            events = history.History(Path(d)).all()
            self.assertEqual([(e["n"], e["kind"]) for e in events],
                             [(1, "mod disabled"), (2, "plugin deactivated"), (3, "mod enabled")])
            self.assertEqual(events[0]["plugins"][0]["position"], 5)
            self.assertEqual(sorted(h.disabled_now()), ["plugin:collection - bramble.esp"])
            with open(Path(d) / "history.jsonl", "ab") as f:
                f.write(b'{"n": 4, "kind": "cut sho')                 # a crash mid-line
            self.assertEqual(len(history.History(Path(d)).all()), 3)


def read_records(data: bytes) -> list[tuple[str, int, list[tuple[str, bytes]]]]:
    """The records of one of ModTrap's own probe plugins: (type, form id, fields). For these tests only."""
    (size,) = struct.unpack_from("<I", data, 4)
    at, out = 24 + size, []
    while at < len(data):
        assert data[at:at + 4] == b"GRUP"
        (gsize,) = struct.unpack_from("<I", data, at + 4)
        label = data[at + 8:at + 12]
        p, end = at + 24, at + gsize
        while p < end:
            sig = data[p:p + 4]
            rsize, _flags, form = struct.unpack_from("<III", data, p + 4)
            assert sig == label
            q, rend, fields = p + 24, p + 24 + rsize, []
            while q < rend:
                (fsize,) = struct.unpack_from("<H", data, q + 4)
                fields.append((data[q:q + 4].decode(), data[q + 6:q + 6 + fsize]))
                q += 6 + fsize
            assert q == rend
            out.append((sig.decode(), form, fields))
            p = rend
        assert p == end
        at = end
    assert at == len(data)
    return out


class ProbeTests(unittest.TestCase):
    def test_the_probe_plugins_are_well_formed_and_say_what_they_should(self):
        files = probe.probe_set()
        probe.check_headers(files)
        self.assertEqual(sorted(files), sorted([probe.BASE, probe.BAD, probe.OVERRIDE, probe.PATCH]))
        base = read_records(files[probe.BASE])
        self.assertEqual([(s, f) for s, f, _ in base], [("MATT", 0x800), ("MATT", 0x801)])
        bad = read_records(files[probe.BAD])                           # Base is 00 in Bad; Bad's own are 01
        self.assertEqual([(s, f) for s, f, _ in bad],
                         [("GLOB", 0x01000800), ("GLOB", 0x01000801), ("MATT", 0x801), ("MATT", 0x01000802)])
        over = read_records(files[probe.OVERRIDE])                     # Base 00, Bad 01, its own 02
        self.assertEqual([(s, f) for s, f, _ in over],
                         [("GLOB", 0x01000800), ("GLOB", 0x02000800), ("FLST", 0x02000801), ("MATT", 0x801)])
        entries = [struct.unpack("<I", b)[0] for t, b in over[2][2] if t == "LNAM"]
        self.assertEqual(entries, [0x02000800, 0x01000801])            # its own global, and one of Bad's
        # Base's brick: its parent is Base's stone; Bad makes it Bad's own material, and Override carries that on.
        parent = lambda recs: [struct.unpack("<I", b)[0] for s, f, fs in recs if (s, f) == ("MATT", 0x801) for t, b in fs if t == "PNAM"]   # noqa: E731
        self.assertEqual((parent(base), parent(bad), parent(over)), ([0x800], [0x01000802], [0x01000802]))
        self.assertIn(probe.PARENT_BAD, files[probe.OVERRIDE])
        self.assertNotIn(probe.PARENT_BACK, files[probe.OVERRIDE])
        patch = read_records(files[probe.PATCH])
        self.assertTrue(all(f >> 24 == 0 for _, f, _ in patch))        # nothing of its own: a patch only
        self.assertEqual(probe.EXPECTED[probe.OVERRIDE]["own"], sum(1 for s, f, _ in over if s == "GLOB" and f >> 24 == 1))

    def test_the_probe_plugins_read_as_a_modlist(self):
        with tempfile.TemporaryDirectory() as d:
            files = probe.probe_set()
            root = fx.make_instance(Path(d) / "List", [("+", "ModTrap Probe", files)],
                                    load_order=[probe.BASE, probe.BAD, probe.OVERRIDE, probe.PATCH])
            m = model.build(instance.load(root))
            self.assertEqual(m.issues, [])
            self.assertEqual(m.row(probe.BAD).dependants, [probe.OVERRIDE, probe.PATCH])
            self.assertEqual(m.row(probe.BASE).dependants, [probe.BAD, probe.OVERRIDE])


class NotReachableTests(unittest.TestCase):
    def test_no_endpoint_changes_a_modlist(self):
        """The groundwork is switched off: the module behind the page's every call imports none of it (WHY§36)."""
        import inspect
        imports = [ln for ln in inspect.getsource(api).splitlines() if ln.startswith(("from ", "import "))]
        named = " ".join(imports).replace(",", " ").split()
        for name in ("profile", "safe", "history", "probe"):
            self.assertNotIn(name, named)


